class Solution(object):
    def countCommas(self, n):
        if n-999>0 and n<=999999:
            return n-999
        elif n>999999 and n<=999999999:
            return ((n-999999)*2)+(999000)
        elif n>999999999 and n<=999999999999:
            return ((n-999999999)*3)+((999000000)*2)+(999000)
        elif n>999999999999 and n<=999999999999999:
            return ((n-999999999999)*4)+(999000000000*3)+(999000000*2)+(999000)
        elif n>999999999999999 and n<=999999999999999999:
            return ((n-999999999999999)*5)+(999000000000000*4)+(999000000000*3)+(999000000*2)+(999000)
        else:
            return 0